"""Refresh the GitHub issue mirrors using the repository's REST issue list."""

import json
from pathlib import Path
import subprocess


ROOT = Path(__file__).resolve().parents[1]


def refresh():
    result = subprocess.run(
        [
            str(Path.home() / "bin/gh"), "api",
            "repos/rbonon/coffeelab/issues?state=all&per_page=100",
            "--paginate", "--slurp",
        ],
        cwd=ROOT,
        text=True,
        stdout=subprocess.PIPE,
        check=True,
    )
    issues = [
        issue for page in json.loads(result.stdout)
        for issue in page if "pull_request" not in issue
    ]
    if not issues:
        raise SystemExit("GitHub returned no issues. Existing mirrors were preserved.")

    groups = {}
    for issue in sorted(issues, key=lambda item: item["number"]):
        milestone = issue["milestone"]
        groups.setdefault(milestone["title"] if milestone else "Unassigned", []).append(issue)

    roadmap = ["# Coffee Lab roadmap", "", "Generated by `scripts/gen-docs.py`."]
    hierarchy = ["# Issue hierarchy", "", "Generated by `scripts/gen-docs.py`."]
    for milestone in sorted(groups):
        roadmap.extend(["", f"## {milestone}", ""])
        hierarchy.extend(["", f"## {milestone}", ""])
        links = {}
        for issue in groups[milestone]:
            title = issue["title"].replace("[", r"\[").replace("]", r"\]")
            link = f'[#{issue["number"]} — {title}]({issue["html_url"]})'
            roadmap.append(f'- {link} ({issue["state"]})')
            kind = "Epic" if issue["title"].startswith("[Epic] ") else "Task"
            links[issue["url"]] = f"- **{kind}** {link}"

        children = {}
        for issue in groups[milestone]:
            parent_url = issue.get("parent_issue_url")
            if parent_url in links:
                children.setdefault(parent_url, []).append(issue["url"])

        sub_issues = {url for urls in children.values() for url in urls}

        def append_issue(url, indent=""):
            hierarchy.append(indent + links[url])
            for child in children.get(url, []):
                append_issue(child, indent + "  ")

        for url in links:
            if url not in sub_issues:
                append_issue(url)

    (ROOT / "ROADMAP.md").write_text("\n".join(roadmap) + "\n", encoding="utf-8")
    (ROOT / "docs/planning/board-hierarchy.md").write_text("\n".join(hierarchy) + "\n", encoding="utf-8")


if __name__ == "__main__":
    refresh()
